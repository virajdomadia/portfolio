import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, it, expect, vi } from 'vitest'
import ContactForm from '@/components/Contact/ContactForm'

describe('ContactForm', () => {
  it('posts and shows the sent state', async () => {
    const fetchMock = vi.fn(async () => new Response(JSON.stringify({ ok: true }), { status: 200 }))
    vi.stubGlobal('fetch', fetchMock)
    render(<ContactForm />)
    await userEvent.click(screen.getByLabelText('A freelance project'))
    await userEvent.type(screen.getByLabelText('Your name'), 'Priya Sharma')
    await userEvent.type(screen.getByLabelText('Email'), 'priya@example.com')
    await userEvent.type(screen.getByLabelText('Message'), 'We need a booking platform built.')
    await userEvent.click(screen.getByRole('button', { name: /Send message/ }))
    await waitFor(() => expect(screen.getByText('Sent.')).toBeInTheDocument())
    expect(JSON.parse((fetchMock.mock.calls[0] as any)[1].body).intent).toBe('project')
    expect(screen.getByRole('status')).toHaveFocus()
    expect(screen.getByRole('status')).toHaveTextContent(/^Sent\. Thanks/)
  })
  it('shows the error with a mailto fallback and keeps the text', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({ error: 'Mail is not configured. Please email me directly.' }), { status: 500 })))
    render(<ContactForm />)
    await userEvent.type(screen.getByLabelText('Your name'), 'Priya Sharma')
    await userEvent.type(screen.getByLabelText('Email'), 'priya@example.com')
    await userEvent.type(screen.getByLabelText('Message'), 'We need a booking platform built.')
    await userEvent.click(screen.getByRole('button', { name: /Send message/ }))
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent(/email me directly/))
    expect(screen.getByLabelText('Message')).toHaveValue('We need a booking platform built.')
    expect(screen.getByRole('alert').querySelector('a')).toHaveAttribute('href', expect.stringContaining('mailto:'))
  })
  it('enforces the server rules in the browser and names the field', async () => {
    const fetchMock = vi.fn(); vi.stubGlobal('fetch', fetchMock)
    render(<ContactForm />)
    const name = screen.getByLabelText('Your name'), email = screen.getByLabelText('Email'), msg = screen.getByLabelText('Message')
    expect(msg).toHaveAttribute('maxLength', '2000'); expect(name).toHaveAttribute('maxLength', '80')
    await userEvent.type(name, '   '); await userEvent.type(email, 'qa@localhost'); await userEvent.type(msg, 'We need a booking platform built.')
    await userEvent.click(screen.getByRole('button', { name: /Send message/ }))
    expect(name).toHaveAttribute('aria-invalid', 'true'); expect(name).toHaveFocus()
    expect(name).toHaveAccessibleDescription(/your name/)
    await userEvent.clear(name); await userEvent.type(name, 'Priya <b>')
    expect(name).not.toHaveAttribute('aria-invalid')
    await userEvent.click(screen.getByRole('button', { name: /Send message/ }))
    expect(name).toHaveAccessibleDescription(/no < or >/)
    await userEvent.clear(name); await userEvent.type(name, 'Priya Sharma')
    await userEvent.click(screen.getByRole('button', { name: /Send message/ }))
    expect(email).toHaveAttribute('aria-invalid', 'true'); expect(email).toHaveAccessibleDescription(/full email address/)
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it('shows the field the server rejected', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({ error: 'Please write a message of 10 to 2,000 characters.', field: 'message' }), { status: 400 })))
    render(<ContactForm />)
    await userEvent.type(screen.getByLabelText('Your name'), 'Priya Sharma')
    await userEvent.type(screen.getByLabelText('Email'), 'priya@example.com')
    await userEvent.type(screen.getByLabelText('Message'), 'We need a booking platform built.')
    await userEvent.click(screen.getByRole('button', { name: /Send message/ }))
    await waitFor(() => expect(screen.getByLabelText('Message')).toHaveAccessibleDescription(/10 to 2,000 characters/))
    expect(screen.queryByRole('alert')).toBeNull()
  })
})
